-- Recorte do modelo do SIGA usado SÓ em teste (Oracle 23 Free via Testcontainers): apenas as tabelas e colunas
-- que o integration.siga lê. Os tipos são hipóteses de teste; o tipo real de cada coluna é conferido na
-- homologação (docs/homologacao/S1-roteiro-homologacao.md). DDL compatível com Oracle 19c.

CREATE USER SIGA2_LICENCIAMENTO IDENTIFIED BY "senha_teste" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER SIGA2_CAMUNDA IDENTIFIED BY "senha_teste" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER SIGA2_OUTORGA IDENTIFIED BY "senha_teste" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER SIGA2_ARRECADACAO IDENTIFIED BY "senha_teste" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;

CREATE TABLE SIGA2_LICENCIAMENTO.TIPO_PROCESSO (
    ID        NUMBER(19)     NOT NULL PRIMARY KEY,
    DESCRICAO VARCHAR2(200)  NOT NULL
);

CREATE TABLE SIGA2_LICENCIAMENTO.PESSOA (
    ID       NUMBER(19)     NOT NULL PRIMARY KEY,
    NOME     VARCHAR2(200),
    CPF_CNPJ VARCHAR2(20)
);

CREATE TABLE SIGA2_LICENCIAMENTO.REQUERIMENTO (
    ID                 NUMBER(19)    NOT NULL PRIMARY KEY,
    NUMERO             VARCHAR2(20),
    NUMERO_PROCESSO    VARCHAR2(20),
    DATA_ABERTURA      TIMESTAMP,
    DATA_ALTERACAO     TIMESTAMP,
    SITUACAO_PROCESSO  VARCHAR2(80),
    ID_PESSOA          NUMBER(19),
    ID_TIPO_PROCESSO   NUMBER(19),
    ID_TIPO_REQUERIMENTO NUMBER(19)
);

CREATE TABLE SIGA2_CAMUNDA.ACT_RE_PROCDEF (
    ID_   VARCHAR2(64)  NOT NULL PRIMARY KEY,
    NAME_ VARCHAR2(255)
);

CREATE TABLE SIGA2_CAMUNDA.ACT_RU_EXECUTION (
    ID_            VARCHAR2(64) NOT NULL PRIMARY KEY,
    PROC_INST_ID_  VARCHAR2(64),
    PARENT_ID_     VARCHAR2(64),
    BUSINESS_KEY_  VARCHAR2(255)
);

CREATE TABLE SIGA2_CAMUNDA.ACT_RU_TASK (
    ID_            VARCHAR2(64) NOT NULL PRIMARY KEY,
    PROC_INST_ID_  VARCHAR2(64),
    PROC_DEF_ID_   VARCHAR2(64),
    NAME_          VARCHAR2(255),
    ASSIGNEE_      NVARCHAR2(255),
    CREATE_TIME_   TIMESTAMP
);

CREATE TABLE SIGA2_LICENCIAMENTO.TIPO_REQUERIMENTO (
    ID        NUMBER(19)     NOT NULL PRIMARY KEY,
    DESCRICAO VARCHAR2(200)  NOT NULL
);

CREATE TABLE SIGA2_LICENCIAMENTO.PRIORIDADE_PROCESSO (
    ID               NUMBER(19) NOT NULL PRIMARY KEY,
    ID_REQUERIMENTO  NUMBER(19) NOT NULL
);

CREATE TABLE SIGA2_LICENCIAMENTO.PRIORIDADE_PROCESSO_CRITERIO (
    ID                          NUMBER(19) NOT NULL PRIMARY KEY,
    ID_PRIORIDADE_PROCESSO      NUMBER(19) NOT NULL,
    ID_TIPO_PRIORIDADE_PROCESSO NUMBER(10) NOT NULL
);

CREATE TABLE SIGA2_LICENCIAMENTO.REQUERIMENTO_LICENCIAMENTO (
    ID                        NUMBER(19) NOT NULL PRIMARY KEY,
    ID_REQUERIMENTO           NUMBER(19) NOT NULL,
    DESCRICAO_ATIVIDADE       VARCHAR2(1000),
    DESCRICAO_GRUPO_ATIVIDADE VARCHAR2(1000)
);

CREATE TABLE SIGA2_LICENCIAMENTO.OBJETIVO_LICENCIAMENTO (
    ID                                  NUMBER(19) NOT NULL PRIMARY KEY,
    ID_REQUERIMENTO_LICENCIAMENTO       NUMBER(19) NOT NULL,
    DESCRICAO_OBJETIVO_LICENCIAMENTO    VARCHAR2(1000)
);

-- Cache do SCORP versionado por inserção: o mesmo CPF pode ter várias linhas, vale a mais recente.
CREATE TABLE SIGA2_LICENCIAMENTO.SERVIDOR (
    ID               NUMBER(19)    NOT NULL PRIMARY KEY,
    CPF              VARCHAR2(11),
    NOME             VARCHAR2(200),
    DATA_ATUALIZACAO TIMESTAMP(6)
);

CREATE TABLE SIGA2_OUTORGA.REQUERIMENTO_OUTORGA (
    ID              NUMBER(19) NOT NULL PRIMARY KEY,
    ID_REQUERIMENTO NUMBER(19) NOT NULL
);

CREATE TABLE SIGA2_OUTORGA.OBJETIVO_OUTORGA (
    ID           NUMBER(19)    NOT NULL PRIMARY KEY,
    DESCRICAO    VARCHAR2(500),
    TIPO_OUTORGA VARCHAR2(30)
);

CREATE TABLE SIGA2_OUTORGA.OBJETIVO_REQUERIMENTO_OUTORGA (
    ID                       NUMBER(19) NOT NULL PRIMARY KEY,
    ID_REQUERIMENTO_OUTORGA  NUMBER(19) NOT NULL,
    ID_OBJETIVO_OUTORGA      NUMBER(19) NOT NULL,
    DATA_FIM                 TIMESTAMP
);

CREATE TABLE SIGA2_OUTORGA.FINALIDADE (
    ID        NUMBER(19)    NOT NULL PRIMARY KEY,
    DESCRICAO VARCHAR2(500)
);

CREATE TABLE SIGA2_OUTORGA.FINALIDADE_ATIVIDADE (
    ID                       NUMBER(19) NOT NULL PRIMARY KEY,
    ID_FINALIDADE            NUMBER(19) NOT NULL,
    ID_ATIVIDADE_ARRECADACAO NUMBER(19)
);

CREATE TABLE SIGA2_OUTORGA.REQUERIMENTO_FINALIDADE_ATIVIDADE (
    ID                      NUMBER(19) NOT NULL PRIMARY KEY,
    ID_REQUERIMENTO         NUMBER(19) NOT NULL,
    ID_FINALIDADE_ATIVIDADE NUMBER(19) NOT NULL
);

CREATE TABLE SIGA2_ARRECADACAO.ATIVIDADE (
    ID        NUMBER(19)     NOT NULL PRIMARY KEY,
    DESCRICAO VARCHAR2(1000)
);

-- Usuário de leitura como será pedido ao DBA: CREATE SESSION + SELECT só no que a S1 e a S1.1 usam.
CREATE USER VISTAS_LEITURA_SIGA IDENTIFIED BY "leitura_teste";
GRANT CREATE SESSION TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.REQUERIMENTO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.PESSOA TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.TIPO_PROCESSO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_CAMUNDA.ACT_RU_EXECUTION TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_CAMUNDA.ACT_RU_TASK TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_CAMUNDA.ACT_RE_PROCDEF TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.TIPO_REQUERIMENTO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.PRIORIDADE_PROCESSO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.PRIORIDADE_PROCESSO_CRITERIO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.REQUERIMENTO_LICENCIAMENTO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.OBJETIVO_LICENCIAMENTO TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_LICENCIAMENTO.SERVIDOR TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_OUTORGA.REQUERIMENTO_OUTORGA TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_OUTORGA.OBJETIVO_OUTORGA TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_OUTORGA.OBJETIVO_REQUERIMENTO_OUTORGA TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_OUTORGA.FINALIDADE TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_OUTORGA.FINALIDADE_ATIVIDADE TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_OUTORGA.REQUERIMENTO_FINALIDADE_ATIVIDADE TO VISTAS_LEITURA_SIGA;
GRANT SELECT ON SIGA2_ARRECADACAO.ATIVIDADE TO VISTAS_LEITURA_SIGA;

-- Usuário que conecta mas não tem grant nenhum: simula "falta de permissão".
CREATE USER SEM_PERMISSAO IDENTIFIED BY "sem_permissao_teste";
GRANT CREATE SESSION TO SEM_PERMISSAO;
