-- Origem IMOVEL: documentos de todos os imóveis do requerimento. IMOVEL.ID_REQUERIMENTO: a confirmar no dicionário.
SELECT 'IMOVEL' AS ORIGEM, di.ID, i.ID_REQUERIMENTO, di.CHAVE, di.TITULO, di.NOME_ARQUIVO,
       NULL AS TIPO, di.DATA_INICIO AS DATA_DOC, di.DATA_FIM, di.SIGILOSO AS SIGILO
FROM   SIGA2_LICENCIAMENTO.IMOVEL i
JOIN   SIGA2_LICENCIAMENTO.DOCUMENTO_IMOVEL di ON di.ID_IMOVEL = i.ID
WHERE  i.ID_REQUERIMENTO = :idRequerimento
