-- Origem RESPONSAVEL_TECNICO. Não filtra HABILITADO, como a Vista. Sigilo: coluna real SIGILO (divergência consciente).
SELECT 'RESPONSAVEL_TECNICO' AS ORIGEM, d.ID, rt.ID_REQUERIMENTO, d.CHAVE, d.NOME_ARQUIVO AS TITULO, d.NOME_ARQUIVO,
       d.TIPO, d.DATA_INICIO AS DATA_DOC, d.DATA_FIM, d.SIGILO
FROM   SIGA2_LICENCIAMENTO.REQUERIMENTO_RESPONSAVEL_TECNICO rt
JOIN   SIGA2_LICENCIAMENTO.REQ_RESP_TECNICO_DOCUMENTO d ON d.ID_REQUERIMENTO_RESP_TECNICO = rt.ID
WHERE  rt.ID_REQUERIMENTO = :idRequerimento
