-- Origem DOCUMENTO_PROCESSO, como a Vista do SIGA: sem filtro de vigência, de grupo ou de chave. Data: criação.
SELECT 'DOCUMENTO_PROCESSO' AS ORIGEM, dp.ID, dp.ID_REQUERIMENTO, dp.CHAVE, dp.TITULO, dp.NOME_ARQUIVO,
       dp.GRUPO_DOCUMENTO AS TIPO, dp.DATA_CRIACAO AS DATA_DOC, dp.DATA_FIM, dp.SIGILOSO AS SIGILO
FROM   SIGA2_LICENCIAMENTO.DOCUMENTO_PROCESSO dp
WHERE  dp.ID_REQUERIMENTO = :idRequerimento
