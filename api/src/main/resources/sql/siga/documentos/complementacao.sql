-- Origem COMPLEMENTACAO: arquivos dos itens e das respostas. A tabela não tem NOME_ARQUIVO: a Vista usa TITULO nos dois campos.
SELECT 'COMPLEMENTACAO' AS ORIGEM, cia.ID, c.ID_REQUERIMENTO, cia.CHAVE_PANDORA AS CHAVE, cia.TITULO,
       cia.TITULO AS NOME_ARQUIVO,
       CASE WHEN cia.ID_COMP_ITEM_RESPOSTA IS NOT NULL THEN 'RESPOSTA' ELSE 'ITEM' END AS TIPO,
       cia.DATA_INICIO AS DATA_DOC, cia.DATA_FIM, cia.SIGILOSO AS SIGILO
FROM   SIGA2_LICENCIAMENTO.COMPLEMENTACAO c
JOIN   SIGA2_LICENCIAMENTO.COMPLEMENTACAO_ITEM ci ON ci.ID_COMPLEMENTACAO = c.ID
JOIN   SIGA2_LICENCIAMENTO.COMPLEMENTACAO_ITEM_ARQUIVO cia ON cia.ID_COMPLEMENTACAO_ITEM = ci.ID
WHERE  c.ID_REQUERIMENTO = :idRequerimento
