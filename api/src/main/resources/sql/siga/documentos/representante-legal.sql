-- Origem REPRESENTANTE_LEGAL. Sigilo: coluna real SIGILO (a Vista do SIGA a ignora; aqui é divergência consciente, D-S2.1).
SELECT 'REPRESENTANTE_LEGAL' AS ORIGEM, d.ID, rl.ID_REQUERIMENTO, d.CHAVE, d.NOME_ARQUIVO AS TITULO, d.NOME_ARQUIVO,
       d.TIPO, d.DATA_INICIO AS DATA_DOC, d.DATA_FIM, d.SIGILO
FROM   SIGA2_LICENCIAMENTO.REQUERIMENTO_REPRESENTANTE_LEGAL rl
JOIN   SIGA2_LICENCIAMENTO.REQ_REP_LEGAL_DOCUMENTO d ON d.ID_REQUERIMENTO_REP_LEGAL = rl.ID
WHERE  rl.ID_REQUERIMENTO = :idRequerimento
