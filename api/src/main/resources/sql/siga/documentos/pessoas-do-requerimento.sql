-- Pessoas do requerimento com documentos pessoais no SCORP (S4): interessado, representantes legais e responsáveis
-- técnicos, com o ID_CORPORATIVO (chave da pessoa no SCORP). Colunas conferidas no banco (P31): REQUERIMENTO.ID_PESSOA,
-- REQUERIMENTO_REPRESENTANTE_LEGAL.ID_PESSOA e REQUERIMENTO_RESPONSAVEL_TECNICO.ID_PESSOA, todas com FK para PESSOA.
-- Só SELECT; ID_CORPORATIVO nulo fica fora; não filtra HABILITADO, como as origens da Vista. A mesma pessoa pode vir em
-- mais de um papel: o domínio faz uma chamada só por pessoa.
SELECT 'INTERESSADO' AS PAPEL, p.ID_CORPORATIVO
FROM   SIGA2_LICENCIAMENTO.REQUERIMENTO r
JOIN   SIGA2_LICENCIAMENTO.PESSOA p ON p.ID = r.ID_PESSOA
WHERE  r.ID = :idRequerimento
AND    p.ID_CORPORATIVO IS NOT NULL
UNION
SELECT 'REPRESENTANTE_LEGAL' AS PAPEL, p.ID_CORPORATIVO
FROM   SIGA2_LICENCIAMENTO.REQUERIMENTO_REPRESENTANTE_LEGAL rl
JOIN   SIGA2_LICENCIAMENTO.PESSOA p ON p.ID = rl.ID_PESSOA
WHERE  rl.ID_REQUERIMENTO = :idRequerimento
AND    p.ID_CORPORATIVO IS NOT NULL
UNION
SELECT 'RESPONSAVEL_TECNICO' AS PAPEL, p.ID_CORPORATIVO
FROM   SIGA2_LICENCIAMENTO.REQUERIMENTO_RESPONSAVEL_TECNICO rt
JOIN   SIGA2_LICENCIAMENTO.PESSOA p ON p.ID = rt.ID_PESSOA
WHERE  rt.ID_REQUERIMENTO = :idRequerimento
AND    p.ID_CORPORATIVO IS NOT NULL
