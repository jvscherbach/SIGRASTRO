-- S8, bloco 5. Plano B: datas e situação do requerimento, por chave primária.
SELECT r.DATA_ABERTURA               AS ABERTURA,
       r.DATA_PROTOCOLO_PROCESSO     AS PROTOCOLO,
       r.DATA_CANCELAMENTO           AS CANCELAMENTO,
       r.DATA_EXPIRACAO_REQUERIMENTO AS EXPIRACAO_REQUERIMENTO,
       r.DATA_EXPIRACAO_PROCESSO     AS EXPIRACAO_PROCESSO,
       r.SITUACAO_PROCESSO           AS SITUACAO
FROM   SIGA2_LICENCIAMENTO.REQUERIMENTO r
WHERE  r.ID = :idRequerimento
FETCH  FIRST 1 ROWS ONLY
