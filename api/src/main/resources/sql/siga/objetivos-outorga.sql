-- Objetivos vigentes de outorga do requerimento (1:N). Só vigentes: DATA_FIM nula ou futura.
-- NÃO CONFIRMADO: nome da coluna OBJETIVO_REQUERIMENTO_OUTORGA.ID_OBJETIVO_OUTORGA (conferir no roteiro S1.1).
SELECT oo.ID, oo.DESCRICAO, oo.TIPO_OUTORGA
FROM   SIGA2_OUTORGA.REQUERIMENTO_OUTORGA ro
JOIN   SIGA2_OUTORGA.OBJETIVO_REQUERIMENTO_OUTORGA oro ON oro.ID_REQUERIMENTO_OUTORGA = ro.ID
JOIN   SIGA2_OUTORGA.OBJETIVO_OUTORGA oo ON oo.ID = oro.ID_OBJETIVO_OUTORGA
WHERE  ro.ID_REQUERIMENTO = :idRequerimento
  AND  (oro.DATA_FIM IS NULL OR oro.DATA_FIM > SYSTIMESTAMP)
ORDER  BY oro.ID
