-- Pares finalidade/atividade de outorga (1:N; remoção física no SIGA, sem vigência). Lista independente dos
-- objetivos: nunca se faz junção entre as duas. A atividade vem de SIGA2_ARRECADACAO.ATIVIDADE; sem linha, nula.
-- NÃO CONFIRMADO: colunas REQUERIMENTO_FINALIDADE_ATIVIDADE.ID_FINALIDADE_ATIVIDADE e
-- FINALIDADE_ATIVIDADE.ID_FINALIDADE (conferir no roteiro S1.1).
SELECT f.DESCRICAO AS FINALIDADE, a.DESCRICAO AS ATIVIDADE
FROM   SIGA2_OUTORGA.REQUERIMENTO_FINALIDADE_ATIVIDADE rfa
JOIN   SIGA2_OUTORGA.FINALIDADE_ATIVIDADE fa ON fa.ID = rfa.ID_FINALIDADE_ATIVIDADE
JOIN   SIGA2_OUTORGA.FINALIDADE f ON f.ID = fa.ID_FINALIDADE
LEFT   JOIN SIGA2_ARRECADACAO.ATIVIDADE a ON a.ID = fa.ID_ATIVIDADE_ARRECADACAO
WHERE  rfa.ID_REQUERIMENTO = :idRequerimento
ORDER  BY f.DESCRICAO, a.DESCRICAO, rfa.ID
